"""
Stage 3: Поразделная генерация регламента.
Каждый раздел генерируется последовательно с контекстом предыдущих.
Stage 6.5: поддержка profile_context для инъекции профиля компании.
"""

import logging
from typing import Optional
from app.providers.base import BaseLLMProvider

logger = logging.getLogger(__name__)

SYSTEM_PROMPT_WRITER = """Ты пишешь КОРПОРАТИВНЫЙ РЕГЛАМЕНТ. Твоя задача — написать ОДИН КОНКРЕТНЫЙ РАЗДЕЛ документа.

Ниже даны:
1. ОБЩИЙ ПЛАН документа (чтобы ты видел контекст всего документа)
2. АННОТАЦИИ всех разделов (чтобы ты знал, что будет в других разделах)
3. КОНЕЦ ПРЕДЫДУЩЕГО РАЗДЕЛА (для логической связки)
4. АННОТАЦИЯ ТЕКУЩЕГО РАЗДЕЛА (что конкретно нужно написать)

ПРАВИЛА НАПИСАНИЯ РАЗДЕЛА (нарушение недопустимо):

1. АКТИВНЫЙ ЗАЛОГ (ЗАПРЕЩЁН пассивный):
   ❌ "производится проверка", "контроль возлагается"
   ✅ "Заведующий складом проверяет", "Главный бухгалтер утверждает"

2. ФОРМУЛА КАЖДОГО ШАГА:
   [Конкретная Должность] в течение [Точный срок] выполняет [Конкретное Действие] и направляет [Результат] в адрес [Кому] посредством [ИТ-система/канал связи]

3. КОНКРЕТНЫЕ СРОКИ (запрещены общие фразы):
   ❌ "своевременно", "периодически", "в установленные сроки", "оперативно"
   ✅ "в течение 3 (трёх) рабочих дней", "не позднее 12:00 следующего дня"

4. НУМЕРАЦИЯ ПУНКТОВ:
   - Используй сквозную нумерацию (3.1, 3.2, 3.3)
   - Каждый пункт — ОДИН шаг процесса
   - Минимум 8 (восемь) пунктов в разделе

5. УСЛОВНАЯ ЛОГИКА ПРИ ОТКЛОНЕНИЯХ:
   Для ключевых шагов пропиши:
   "Если [условие], то [должность] выполняет [действие 1]. Если [другое условие], то [действие 2]."

6. ССЫЛКИ НА ПРИЛОЖЕНИЯ:
   Если в шаге создаётся документ, укажи: "...формирует Акт о приёмке (Приложение N)"
   Номера приложений делай сквозными (Приложение 1, Приложение 2...)

7. СВЯЗЬ С ПРЕДЫДУЩИМ РАЗДЕЛОМ:
   Начни раздел с 1-2 предложений, которые связывают его с предыдущим:
   "После утверждения плана закупок (Раздел 2) осуществляется непосредственная поставка..."
"""


async def generate_section(
    provider: BaseLLMProvider,
    topic: str,
    section_number: int,
    section_title: str,
    section_annotation: str,
    plan_with_annotations: str,
    previous_section_tail: str,
    profile_context: Optional[str] = None,
) -> str:
    """Сгенерировать один раздел регламента."""
    context_parts = []
    context_parts.append(f"===== ОБЩИЙ ПЛАН ДОКУМЕНТА =====\n{plan_with_annotations}")
    if previous_section_tail:
        context_parts.append(f"\n===== КОНЕЦ ПРЕДЫДУЩЕГО РАЗДЕЛА =====\n{previous_section_tail}")
    context_parts.append(f"\n===== ЗАДАНИЕ =====\nНапиши ПОЛНЫЙ ТЕКСТ раздела {section_number}: \"{section_title}\"")
    context_parts.append(f"Аннотация раздела: {section_annotation}")

    # Инъекция профиля компании
    if profile_context:
        context_parts.append(f"\n\n{profile_context}")
        context_parts.append(
            "\n\nИспользуй типовые шаблоны шагов и словарь терминов из профиля компании. "
            "Придерживайся указанных должностей, систем и документов. "
            "Формулируй шаги в соответствии с шаблонами из профиля."
        )

    context_parts.append("\nНачни с логической связки с предыдущим разделом.")
    context_parts.append("Опиши каждый шаг по формуле: кто, что, когда, как, в какой системе.")
    context_parts.append("Добавь алгоритмы действий при отклонениях.")
    context_parts.append("Минимум 8 (восемь) нумерованных пунктов.")
    user_prompt = "\n".join(context_parts)

    logger.info("Stage 3: Generating section %d '%s'", section_number, section_title)
    raw = await provider.generate(
        prompt=user_prompt,
        system_prompt=SYSTEM_PROMPT_WRITER,
        temperature=0.7,
        max_tokens=8192,
    )
    return raw.strip()
